//! The C ABI, in one file.
//!
//! Phase 12 decision 5, applied at increment 5h.  Every symbol a C caller can
//! reach is an entry point here calling ordinary Zig, and `@export` appears
//! nowhere else under `src/zig` -- so the export check is a grep over this
//! file rather than a checked-in list the build diffs, which is what item 9
//! was before decision 5 deleted it.
//!
//! **Why it had to exist before the type pass.**  A slice has no guaranteed
//! in-memory representation, so Zig refuses one in a `callconv(.c)` signature,
//! and `export fn` forces that calling convention.  While a runtime function
//! published its own symbol it could not take a slice.  `DESIGN.md` section 9
//! has the measurement: 890 of the 1,981 `[*c]` sites were held there.
//!
//! **The gating is this file's too.**  A file is analysed when something
//! *references* one of its declarations -- rule 71 -- so the condition around
//! an `@export` below is what decides whether the subsystem behind it is
//! compiled at all.  The bare `@import`s are inert on their own.  The
//! conditions are `root.zig`'s comptime block and the guards the sources
//! already carried, spelled against `options` and `config` rather than against
//! a file-local `const`.
//!
//! **Two populations, and the second is not a shortcut.**  566 symbols get an
//! entry point that calls an ordinary Zig function.  The other 130 are
//! `@export`ed directly, because the thing they name is *already* a dedicated
//! C-ABI shim with no other caller -- `raise.panicking(f).abi`, or one of
//! `args.zig`'s generated getters.  Those have no second hat to take off.
//! Generated by `./port/capi.janet`; edit that rather than this.

